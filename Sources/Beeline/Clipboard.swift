import AppKit
import Carbon.HIToolbox

final class Clipboard {
    struct Entry {
        let text: String
        let copied: Date
        let app: String?
        let icon: NSImage?
    }

    private(set) var entries: [Entry] = []
    private let board: NSPasteboard
    private var lastChange: Int
    private var timer: Timer?
    private var generation = 0

    init(board: NSPasteboard = .general) {
        self.board = board
        lastChange = board.changeCount
    }

    /// Types that password managers and similar apps use to say "do not keep this".
    private static let doNotKeep: [NSPasteboard.PasteboardType] = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType",
    ].map { NSPasteboard.PasteboardType(rawValue: $0) }

    func start() {
        syncWithSetting()
        NotificationCenter.default.addObserver(forName: UserDefaults.didChangeNotification, object: nil, queue: .main) { [weak self] _ in
            self?.syncWithSetting()
        }
    }

    private func syncWithSetting() {
        if Settings.isOn(Settings.clipboardHistory) {
            guard timer == nil else { return }
            lastChange = board.changeCount
            timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.check() }
        } else {
            timer?.invalidate()
            timer = nil
            generation += 1
            entries.removeAll()
        }
    }

    func clear() {
        generation += 1
        entries.removeAll()
    }

    static func mayKeep(_ types: [NSPasteboard.PasteboardType]) -> Bool {
        !types.contains(where: { doNotKeep.contains($0) })
    }

    /// An app that supplies its copy lazily (a huge spreadsheet range, a remote desktop) renders it only
    /// when asked, so a read can stall.
    let readQueue = DispatchQueue(label: "beeline.clipboard", qos: .utility)

    func check() {
        let board = self.board
        guard board.changeCount != lastChange else { return }
        let change = board.changeCount
        lastChange = change
        guard Settings.isOn(Settings.clipboardHistory), Self.mayKeep(board.types ?? []) else { return }
        let source = NSWorkspace.shared.frontmostApplication
        let asked = generation
        readQueue.async { [weak self] in
            guard let text = board.string(forType: .string),
                  text.utf16.count <= 200_000,
                  !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
                  board.changeCount == change, Self.mayKeep(board.types ?? []) else { return }
            DispatchQueue.main.async {
                guard let self, self.generation == asked, Settings.isOn(Settings.clipboardHistory) else { return }
                self.entries.removeAll { $0.text == text }
                self.entries.insert(Entry(text: text, copied: Date(), app: source?.localizedName, icon: source?.icon), at: 0)
                if self.entries.count > 100 { self.entries.removeLast(self.entries.count - 100) }
            }
        }
    }

    func results(for query: String, limit: Int) -> [Item]? {
        let words = query.lowercased().split(separator: " ").map(String.init)
        guard let first = words.first, ["clip", "clipboard", "clips", "copied", "paste"].contains(first) else { return nil }
        var filter = words.dropFirst().joined(separator: " ")
        let linksOnly = filter == "links" || filter == "link"
        if linksOnly { filter = "" }
        let relative = RelativeDateTimeFormatter()
        relative.unitsStyle = .short
        let matching = entries
            .filter { filter.isEmpty || $0.text.lowercased().contains(filter) }
            .filter { !linksOnly || $0.text.hasPrefix("http://") || $0.text.hasPrefix("https://") }
        guard !matching.isEmpty else { return nil }
        return matching
            .prefix(limit)
            .enumerated()
            .map { index, entry in
                let line = entry.text.split(whereSeparator: \.isNewline).first.map(String.init) ?? entry.text
                let shown = line.split(whereSeparator: \.isWhitespace).joined(separator: " ")
                return Item(id: "clip:\(index):\(entry.copied.timeIntervalSince1970)", kind: .clipboard, verb: "Paste",
                            title: String(shown.prefix(90)),
                            subtitle: [entry.app, relative.localizedString(for: entry.copied, relativeTo: Date())]
                                .compactMap { $0 }.joined(separator: " · "),
                            keywords: "", icon: entry.icon ?? NSImage(systemSymbolName: "doc.on.clipboard", accessibilityDescription: nil)) {
                    Self.paste(entry.text)
                }
            }
    }

    private static func paste(_ text: String) {
        NSPasteboard.general.clearContents()
        NSPasteboard.general.setString(text, forType: .string)
        let target = NSWorkspace.shared.frontmostApplication?.processIdentifier
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.12) {
            guard NSWorkspace.shared.frontmostApplication?.processIdentifier == target else { return }
            if !Keyboard.press("v", flags: .maskCommand) {
                Actions.report("Allow Accessibility for Beeline in Privacy & Security to paste. The text is on the clipboard.")
            }
        }
    }
}
