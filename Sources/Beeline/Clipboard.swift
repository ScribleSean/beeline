import AppKit
import Carbon.HIToolbox

/// Keeps the last 100 pieces of text you copied, in memory only, so "clip" can paste one again.
/// Nothing is written to disk, and the history ends when Beeline quits. Anything a password manager
/// marks as concealed or transient is never recorded.
final class Clipboard {
    struct Entry {
        let text: String
        let copied: Date
    }

    private(set) var entries: [Entry] = []
    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?

    /// Types that password managers and similar apps use to say "do not keep this".
    private static let doNotKeep: [NSPasteboard.PasteboardType] = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType",
    ].map { NSPasteboard.PasteboardType(rawValue: $0) }

    func start() {
        // Checking twice a second costs next to nothing: the change count is a single integer.
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.check() }
    }

    func clear() {
        entries.removeAll()
    }

    private func check() {
        let board = NSPasteboard.general
        guard board.changeCount != lastChange else { return }
        lastChange = board.changeCount
        guard Settings.isOn(Settings.clipboardHistory),
              !(board.types ?? []).contains(where: { Self.doNotKeep.contains($0) }),
              let text = board.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        // Copying something already in the list moves it to the top instead of repeating it.
        entries.removeAll { $0.text == text }
        entries.insert(Entry(text: text, copied: Date()), at: 0)
        if entries.count > 100 { entries.removeLast(entries.count - 100) }
    }

    /// "clip" lists recent entries; "clip invoice" narrows them to ones containing "invoice".
    func results(for query: String, limit: Int) -> [Item]? {
        let words = query.lowercased().split(separator: " ").map(String.init)
        guard let first = words.first, ["clip", "clipboard", "clips", "copied", "paste"].contains(first) else { return nil }
        let filter = words.dropFirst().joined(separator: " ")
        let relative = RelativeDateTimeFormatter()
        relative.unitsStyle = .short
        return entries
            .filter { filter.isEmpty || $0.text.lowercased().contains(filter) }
            .prefix(limit)
            .enumerated()
            .map { index, entry in
                let line = entry.text.split(whereSeparator: \.isNewline).first.map(String.init) ?? entry.text
                let shown = line.split(whereSeparator: \.isWhitespace).joined(separator: " ")
                return Item(id: "clip:\(index):\(entry.copied.timeIntervalSince1970)", kind: .clipboard, verb: "Paste",
                            title: String(shown.prefix(90)), subtitle: relative.localizedString(for: entry.copied, relativeTo: Date()),
                            keywords: "", icon: NSImage(systemSymbolName: "doc.on.clipboard", accessibilityDescription: nil)) {
                    Self.paste(entry.text)
                }
            }
    }

    /// Puts the text back on the clipboard and pastes it into the app in front, as Cmd+V would.
    private static func paste(_ text: String) {
        NSPasteboard.general.clearContents()
        NSPasteboard.general.setString(text, forType: .string)
        // A moment for the bar to close and the app in front to take keystrokes again.
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.12) {
            for isDown in [true, false] {
                let event = CGEvent(keyboardEventSource: nil, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: isDown)
                event?.flags = .maskCommand
                event?.post(tap: .cghidEventTap)
            }
        }
    }
}
